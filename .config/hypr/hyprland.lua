local meta      = "SUPER"
local navMod    = "SUPER + CTRL"
local launchMod = "CTRL + ALT"
-- NB: these were Shift_L&Alt_L / Control_L&Shift_L&Alt_L in the old hyprlang
-- config, but that never actually bound side-specific keys -- hyprlang
-- substring-matched the uppercased string, so they resolved to plain
-- SHIFT+ALT and CTRL+SHIFT+ALT. Lua parses *_L as keysyms instead, which
-- silently drops them from the modmask, so spell the modifiers out.
local moveMod   = "SHIFT + ALT"
local meh       = "CTRL + SHIFT + ALT"

hl.bind(meta .. " + Return", hl.dsp.exec_cmd(terminal))
hl.bind(meta .. " + Q", hl.dsp.window.close())
hl.bind(meta .. " + E", hl.dsp.exec_cmd(fileManager))
hl.bind(meta .. " + B", hl.dsp.exec_cmd(browser))
hl.bind(navMod .. " + R", hl.dsp.exec_cmd("~/.config/hypr/scripts/restart-waybar.sh"))
hl.bind(meta .. " + SHIFT + V", hl.dsp.exec_cmd("cliphist list | " .. menu .. " -dmenu | cliphist decode | wl-copy"))
hl.bind(meh .. " + Escape", hl.dsp.exec_cmd("pkill " .. menu .. " || " .. menu .. " -show combi"))
hl.bind(meh .. " + Q", hl.dsp.exec_cmd(menu .. " -show p -modi p:rofi-power-menu"))

-- macOS-style clipboard: Super+C/V/X = copy/paste/cut (Ctrl+Shift+* inside terminals).
-- Add more (e.g. select-all on A) by extending mac-clipboard.sh.
hl.bind(meta .. " + C", hl.dsp.exec_cmd("~/.config/hypr/scripts/mac-clipboard.sh copy"))
hl.bind(meta .. " + V", hl.dsp.exec_cmd("~/.config/hypr/scripts/mac-clipboard.sh paste"))
hl.bind(meta .. " + X", hl.dsp.exec_cmd("~/.config/hypr/scripts/mac-clipboard.sh cut"))

-- macOS-style screenshots (grim + slurp). Ctrl variant = clipboard vs. file.
--   Cmd+Shift+3 / +4 / +5      -> full / region / window  to file
--   Cmd+Ctrl+Shift+3 / +4 / +5 -> same, to clipboard
for key, mode in pairs({ ["3"] = "full", ["4"] = "region", ["5"] = "window" }) do
    hl.bind(meta .. " + SHIFT + " .. key,
        hl.dsp.exec_cmd("~/.config/hypr/scripts/screenshot.sh " .. mode .. " file"))
    hl.bind(navMod .. " + SHIFT + " .. key,
        hl.dsp.exec_cmd("~/.config/hypr/scripts/screenshot.sh " .. mode .. " clipboard"))
end

-- Annotate a region in satty (markup, then save + copy)
hl.bind(meta .. " + SHIFT + 6", hl.dsp.exec_cmd("~/.config/hypr/scripts/screenshot.sh region annotate"))

-- Media keys, routed through swayosd-client so they show an on-screen display.
-- No brightness binds: this box has no backlight device (external DP monitor),
-- so brightnessctl would be a no-op. ddcutil would be the route if wanted.
local osd = "swayosd-client "
hl.bind("XF86AudioRaiseVolume", hl.dsp.exec_cmd(osd .. "--output-volume raise"), { locked = true, repeating = true })
hl.bind("XF86AudioLowerVolume", hl.dsp.exec_cmd(osd .. "--output-volume lower"), { locked = true, repeating = true })
hl.bind("XF86AudioMute", hl.dsp.exec_cmd(osd .. "--output-volume mute-toggle"), { locked = true })
hl.bind("XF86AudioMicMute", hl.dsp.exec_cmd(osd .. "--input-volume mute-toggle"), { locked = true })

-- Precise 1% steps with ALT held
hl.bind("ALT + XF86AudioRaiseVolume", hl.dsp.exec_cmd(osd .. "--output-volume +1"), { locked = true, repeating = true })
hl.bind("ALT + XF86AudioLowerVolume", hl.dsp.exec_cmd(osd .. "--output-volume -1"), { locked = true, repeating = true })

-- Requires playerctl
hl.bind("XF86AudioNext", hl.dsp.exec_cmd(osd .. "--playerctl next"), { locked = true })
hl.bind("XF86AudioPrev", hl.dsp.exec_cmd(osd .. "--playerctl prev"), { locked = true })
hl.bind("XF86AudioPlay", hl.dsp.exec_cmd(osd .. "--playerctl play-pause"), { locked = true })
hl.bind("XF86AudioPause", hl.dsp.exec_cmd(osd .. "--playerctl play-pause"), { locked = true })

-- Launch apps
hl.bind(launchMod .. " + F", hl.dsp.exec_cmd("firefox"))
hl.bind(launchMod .. " + G", hl.dsp.exec_cmd("chat-gpt"))

-- Move focus / swap window (vim keys)
local directions = { h = "left", l = "right", k = "up", j = "down" }
for key, dir in pairs(directions) do
    hl.bind(navMod .. " + " .. key, hl.dsp.focus({ direction = dir }))
    hl.bind(moveMod .. " + " .. key, hl.dsp.window.swap({ direction = dir }))
end

-- Switch workspaces / move active window to a workspace
for i = 1, 10 do
    local key = i % 10 -- 10 maps to key 0
    hl.bind(navMod .. " + " .. key, hl.dsp.focus({ workspace = i }))
    hl.bind(moveMod .. " + " .. key, hl.dsp.window.move({ workspace = i }))
end

-- Relative workspace switching
hl.bind(navMod .. " + left", hl.dsp.focus({ workspace = "e-1" }))
hl.bind(navMod .. " + right", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(meta .. " + mouse_down", hl.dsp.focus({ workspace = "e+1" }))
hl.bind(meta .. " + mouse_up", hl.dsp.focus({ workspace = "e-1" }))

-- Move/resize windows with ALT + LMB/RMB and dragging
hl.bind("ALT + mouse:272", hl.dsp.window.drag(), { mouse = true })
hl.bind("ALT + mouse:273", hl.dsp.window.resize(), { mouse = true })


