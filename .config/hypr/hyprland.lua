-- Blur behind the volume/media OSD so it lifts off the wallpaper (macOS-style).
-- ignore_alpha skips blurring the fully transparent area outside the pill, so
-- only the panel itself is frosted.
hl.layer_rule({
    name  = "blur-swayosd",
    match = { namespace = "^swayosd$" },
    blur = true,
    ignore_alpha = 0.2,
})

hl.window_rule({
    name  = "no-border-when-floating",
    match = { float = true },
    border_size = 0,
})

for _, class in ipairs({ "^(1Password)$", "^(Tandem)$", "^(Rofi|rofi)$", "^(Volume Control)$", "^(kitty-float)$" }) do
    hl.window_rule({
        name  = "float-" .. class,
        match = { class = class },
        float = true,
    })
end

hl.window_rule({
    name  = "rofi-stay-focused",
    match = { class = "^(Rofi|rofi)$" },
    stay_focused = true,
})

hl.window_rule({
    -- Ignore maximize requests from all apps. You'll probably like this.
    name  = "suppress-maximize-events",
    match = { class = ".*" },
    suppress_event = "maximize",
})
